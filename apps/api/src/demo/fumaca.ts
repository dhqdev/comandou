const CUSTOMERS: DemoCustomer[] = (() => {
  const out: DemoCustomer[] = [];
  const seen = new Set<string>();
  for (let i = 0; out.length < 180; i++) {
    const name = `${FIRST[i % FIRST.length]} ${LAST[(i * 7 + Math.floor(i / FIRST.length)) % LAST.length]}`;
    if (seen.has(name)) continue;
    seen.add(name);
    const n = out.length;
    const [street, district, lat, lng] = STREETS[(n * 5) % STREETS.length]!;
    const jitter = (k: number) => (((n * k) % 17) - 8) * 0.00018;
    out.push({
      name,
      phone: `119${String(71000000 + n * 21391).slice(0, 8)}`,
      street,
      number: String(40 + ((n * 137) % 1900)),
      district,
      lat: Math.round((lat + jitter(7)) * 1e6) / 1e6,
      lng: Math.round((lng + jitter(11)) * 1e6) / 1e6,
      ...(n === 0 ? { notes: 'Cliente da demonstração: senha cliente123' } : {}),
      ...(n === 3 ? { notes: 'Alérgica a amendoim: avisar a cozinha' } : {}),
      ...(n === 7 ? { notes: 'Sempre pede o ponto bem passado' } : {}),
    });
  }
  return out;
})();
