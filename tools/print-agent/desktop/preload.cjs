// Ponte entre a tela (sem acesso ao Node) e o processo principal.
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('agent', {
  state: () => ipcRenderer.invoke('state'),
  connect: (code) => ipcRenderer.invoke('connect', code),
  disconnect: () => ipcRenderer.invoke('disconnect'),
  printers: () => ipcRenderer.invoke('printers'),
  ports: () => ipcRenderer.invoke('ports'),
  scanNetwork: () => ipcRenderer.invoke('scan-network'),
  discover: (force) => ipcRenderer.invoke('discover', force),
  onScanProgress: (fn) => ipcRenderer.on('scan-progress', (_e, p) => fn(p)),
  setPrinter: (target, spec) => ipcRenderer.invoke('set-printer', target, spec),
  updateCheck: () => ipcRenderer.invoke('update-check'),
  updateInstall: () => ipcRenderer.invoke('update-install'),
  testPrint: (spec) => ipcRenderer.invoke('test-print', spec),
  setAutostart: (on) => ipcRenderer.invoke('set-autostart', on),
  setNotifications: (on) => ipcRenderer.invoke('set-notifications', on),
  openPanel: () => ipcRenderer.invoke('open-panel'),
  reconnect: () => ipcRenderer.invoke('reconnect'),
  checkHost: (host) => ipcRenderer.invoke('check-host', host),
  printerStatus: (spec) => ipcRenderer.invoke('printer-status', spec),
  checkAll: () => ipcRenderer.invoke('check-all'),
  usbCandidates: () => ipcRenderer.invoke('usb-candidates'),
  usbInstall: (id, label) => ipcRenderer.invoke('usb-install', id, label),
  netInstall: (host, label, path) => ipcRenderer.invoke('net-install', host, label, path),
  btPaired: () => ipcRenderer.invoke('bt-paired'),
  btBind: (mac) => ipcRenderer.invoke('bt-bind', mac),
  btSettings: (what) => ipcRenderer.invoke('bt-settings', what),
  bleScan: () => ipcRenderer.invoke('ble-scan'),
  bleChoose: (id) => ipcRenderer.invoke('ble-choose', id),
  bleCancel: () => ipcRenderer.invoke('ble-cancel'),
  onBleDevices: (fn) => ipcRenderer.on('ble-devices', (_e, list) => fn(list)),
  onState: (fn) => ipcRenderer.on('state', (_e, s) => fn(s)),
  onLink: (fn) => ipcRenderer.on('link', (_e, l) => fn(l)),
});
